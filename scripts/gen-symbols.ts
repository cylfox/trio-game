/**
 * Generates src/lib/symbol-data.ts from the pixel-art symbols (assets/pixel-symbols.json, the
 * output of the pixel-symbol tools). Only the size named by the JSON's "size" key is kept.
 *   npm run symbols                 (reads assets/pixel-symbols.json)
 *   npm run symbols -- path/to.json [size]   e.g. a full export and "26x13"
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const input = resolve(process.argv[2] ?? resolve(root, 'assets/pixel-symbols.json'));
const output = resolve(root, 'src/lib/symbol-data.ts');

const SHAPES = ['diamond', 'squiggle', 'oval'] as const;
const SHADINGS = ['solid', 'striped', 'open'] as const;
const COLORS = ['red', 'green', 'purple'] as const;

interface PixelArt {
  size?: string;
  sizes: Record<string, Record<string, Record<string, string[]>>>;
  colors: Record<string, string>;
}

const art = JSON.parse(readFileSync(input, 'utf8')) as PixelArt;
const size = process.argv[3] ?? art.size;
if (size === undefined || !(size in art.sizes)) throw new Error(`pick a size: ${Object.keys(art.sizes).join(', ')}`);
const match = /^(\d+)x(\d+)$/.exec(size);
if (match === null) throw new Error(`bad size ${size}`);
const width = Number(match[1]);
const height = Number(match[2]);

const grids = art.sizes[size];
for (const shape of SHAPES) {
  for (const shading of SHADINGS) {
    const rows = grids[shape]?.[shading];
    if (!Array.isArray(rows) || rows.length !== height) throw new Error(`${shape} ${shading}: expected ${height} rows`);
    rows.forEach((row, y) => {
      if (row.length !== width || !/^[.#o+]+$/.test(row)) throw new Error(`${shape} ${shading} row ${y}: bad row "${row}"`);
    });
  }
}
for (const color of COLORS) {
  if (!/^#[0-9a-f]{6}$/i.test(art.colors[color] ?? '')) throw new Error(`bad colors.${color}`);
}

const gridSource = SHAPES.map(
  (shape) =>
    `  ${shape}: {\n` +
    SHADINGS.map((shading) => `    ${shading}: [\n${grids[shape][shading].map((row) => `      '${row}',`).join('\n')}\n    ],`).join('\n') +
    `\n  },`,
).join('\n');

const source = `// GENERATED by scripts/gen-symbols.ts from assets/pixel-symbols.json (size ${size}).
// Do not edit; run \`npm run symbols\`. The renderer is in symbols.ts.
//
// Legend: '.' empty (the card shows through), '#' symbol colour, 'o' rim and '+' highlight
// (solid only; drawn in the symbol colour while the bevel is off).
import type { Color, Shading, Shape } from './engine/engine.ts';

export const GRID_WIDTH = ${width};
export const GRID_HEIGHT = ${height};

export const SYMBOL_COLORS: Readonly<Record<Color, string>> = {
${COLORS.map((c) => `  ${c}: '${art.colors[c]}',`).join('\n')}
};

export const SYMBOL_GRIDS: Readonly<Record<Shape, Readonly<Record<Shading, readonly string[]>>>> = {
${gridSource}
};
`;

writeFileSync(output, source);
console.log(`wrote ${output} (${size})`);
